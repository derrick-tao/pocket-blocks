import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const base=process.env.TEST_URL || 'http://127.0.0.1:4173/';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox']});
const errors=[];
await mkdir('test-results',{recursive:true});
try {
  const context=await browser.newContext({viewport:{width:1280,height:1080},reducedMotion:'reduce'});
  const page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base);await page.locator('#start').waitFor();
  assert.equal(await page.title(),'Pocket Blocks — A little room for a classic');
  await page.screenshot({path:'test-results/desktop-ready.png',fullPage:true});
  await page.keyboard.press('Enter');assert.equal(await page.locator('#overlay').isVisible(),false);
  await page.keyboard.press('ArrowUp');await page.keyboard.press('ArrowLeft');await page.keyboard.press('Space');
  assert.ok(Number(await page.locator('#score').innerText())>0);
  await page.keyboard.press('p');assert.equal(await page.locator('#overlay-title').innerText(),'Take a breath.');
  const paused=await page.locator('#score').innerText();await page.keyboard.press('Space');
  assert.equal(await page.locator('#score').innerText(),paused);
  await page.keyboard.press('Enter');
  await page.locator('#sound').click();assert.equal(await page.locator('#sound').getAttribute('aria-pressed'),'true');
  await page.locator('#help').click();assert.equal(await page.locator('#instructions').isVisible(),true);
  await page.keyboard.press('Escape');assert.equal(await page.locator('#instructions').isVisible(),false);
  await page.waitForFunction(()=>document.activeElement?.id==='game-area');
  assert.equal(await page.locator('#overlay').isVisible(),true);
  await page.keyboard.press('Enter');
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  assert.equal(await page.locator('#overlay-title').innerText(),'Take a breath.');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#overlay').isVisible(),false);
  await page.screenshot({path:'test-results/desktop-playing.png',fullPage:true});
  for(let n=0;n<35 && !(await page.locator('#overlay').isVisible());n++)await page.keyboard.press('Space');
  assert.equal(await page.locator('#overlay-title').innerText(),'One more?');
  const best=await page.locator('#best').innerText();assert.ok(Number(best.replaceAll(',',''))>0);
  await page.reload();assert.equal(await page.locator('#best').innerText(),best);
  await page.locator('#start').click();
  page.once('dialog',dialog=>dialog.accept());await page.locator('#restart').click();
  assert.equal(await page.locator('#score').innerText(),'000000');
  await context.close();
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
  const phone=await mobile.newPage();phone.on('pageerror',error=>errors.push(error.message));
  await phone.goto(base);await phone.locator('#start').tap();
  await phone.locator('[data-action=cw]').tap();await phone.locator('[data-action=left]').tap();
  await phone.locator('[data-action=drop]').tap();assert.ok(Number(await phone.locator('#score').innerText())>0);
  const down=await phone.locator('[data-action=down]').boundingBox();
  await phone.mouse.move(down.x+down.width/2,down.y+down.height/2);await phone.mouse.down();
  const softScore=Number(await phone.locator('#score').innerText());
  await phone.waitForTimeout(260);
  assert.ok(Number(await phone.locator('#score').innerText())>softScore);
  await phone.locator('[data-action=down]').dispatchEvent('pointercancel',{pointerId:1});
  const cancelled=await phone.locator('#score').innerText();
  await phone.waitForTimeout(160);assert.equal(await phone.locator('#score').innerText(),cancelled);
  await phone.mouse.up();
  await phone.locator('#pause').tap();assert.equal(await phone.locator('#overlay-title').innerText(),'Take a breath.');
  await phone.locator('#start').tap();
  assert.ok(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await phone.screenshot({path:'test-results/mobile-playing.png',fullPage:true});
  await phone.setViewportSize({width:320,height:640});
  assert.ok(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await phone.screenshot({path:'test-results/mobile-small.png',fullPage:true});
  await mobile.close();
  const blocked=await browser.newContext();
  await blocked.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new Error('Storage disabled');}}));
  const storagePage=await blocked.newPage();storagePage.on('pageerror',error=>errors.push(error.message));
  await storagePage.goto(base);await storagePage.locator('#start').click();await storagePage.keyboard.press('Space');
  assert.ok(Number(await storagePage.locator('#score').innerText())>0);await blocked.close();
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: keyboard, touch, pause, game over, restart, persistence, blocked storage, 320px layout; no page errors.');
} finally { await browser.close(); }
